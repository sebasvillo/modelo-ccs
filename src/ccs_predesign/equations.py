"""Equation catalog: the single source for every equation the model uses.

Each entry carries LaTeX, a plain-language meaning (ES/EN), its symbols with units, provenance
(theory | literature | own_closure), a reference key, a validity range and the functions that
implement it. Every implementing function cites the equation id in its docstring
(tests/test_equations.py). The website reads the exported equations.json at build time:

    uv run python -m ccs_predesign.equations equations.json
"""

import json
import sys
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict

Provenance = Literal["theory", "literature", "own_closure"]


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class Reference(_Frozen):
    key: str
    citation: str


class Symbol(_Frozen):
    key: str
    latex: str
    unit: str
    es: str
    en: str


class Equation(_Frozen):
    id: str
    title_es: str
    title_en: str
    latex: str
    meaning_es: str
    meaning_en: str
    symbols: tuple[str, ...]
    provenance: Provenance
    reference: str | None = None
    validity: str | None = None
    implemented_by: tuple[str, ...]
    errata: tuple[str, ...] = ()


