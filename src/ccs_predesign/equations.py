def catalog() -> dict:
    """JSON-ready catalog: equations, symbols and references."""
    return {
        "equations": [e.model_dump() for e in EQUATIONS.values()],
        "symbols": {k: s.model_dump() for k, s in SYMBOLS.items()},
        "references": {k: r.model_dump() for k, r in REFERENCES.items()},
    }


def export_json(path: str | Path) -> None:
    Path(path).write_text(
        json.dumps(catalog(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


